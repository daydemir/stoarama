"""Reproducible offline bundle embedded in the self-updating NAS client.

Run from any directory. Requires Go 1.26.5; no publishing callpoint.
"""
import base64
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import tarfile

root = Path(__file__).resolve().parent
subprocess.run(['go','build','-trimpath','-ldflags=-s -w -buildid=','-o',str(root/'remeasure-linux-amd64'),'./cmd/remeasure'],
               cwd=root/'producer', env=dict(os.environ,CGO_ENABLED='0',GOOS='linux',GOARCH='amd64',GOAMD64='v1',GOTOOLCHAIN='go1.26.5'),check=True)
files = {str(p.relative_to(root)):p.read_bytes() for p in sorted(root.rglob('*'))
         if p.is_file() and p.name not in ('manifest.json','build.py','README.md','.gitignore') and '__pycache__' not in p.parts}
manifest = dict(policy='v85r', files={n:hashlib.sha256(v).hexdigest() for n,v in files.items()},
                upstream_veto_sha256={'source71.json': 'e40e51284fbe2ec6d6da7f4bf8a5cb7bbd50478f7b2f7d46ee94c299c0dbe07f', 'human12.json': 'd09e6aee5deadbbd1421ce14fdcc236dbf1b08ca40e21cd39a70951f988e0e60', 'visual6.json': 'ca882d93697e3e99066a412b512124cc7ff758f38f77364dda2df6d58ec63883'},
                original_linux_evaluator_sha256='edd5ad0cbba75444489d2d1cbd62ed6c6bc9b38adaca38c1819f1d8ae57aeb00',
                october_ffmpeg_sha256='2388de8e05ad71c913ee1a9c4504a1aa5de09ac100a1de92858dd9ec08e9f98b',
                october_ffprobe_sha256='9b2bac862606a48f5bc36091d38e5334cf241538a6f4cc47c60f68e7973a365c')
raw = (json.dumps(manifest,indent=2,sort_keys=True)+'\n').encode();(root/'manifest.json').write_bytes(raw)
files['manifest.json']=raw
buf=io.BytesIO()
with tarfile.open(fileobj=buf,mode='w') as archive:
 for name,body in sorted(files.items()):
  info=tarfile.TarInfo(name);info.size=len(body);info.mode=0o700 if name=='remeasure-linux-amd64' else 0o600
  archive.addfile(info,io.BytesIO(body))
blob=gzip.compress(buf.getvalue(),mtime=0)
client=root.parent/'stoarama_pull.py';s=client.read_text();start='# BEGIN GENERATED V85R BUNDLE';end='# END GENERATED V85R BUNDLE'
block=start+'\nV85R_MANIFEST_SHA = '+repr(hashlib.sha256(raw).hexdigest())+'\nV85R_BUNDLE_SHA = '+repr(hashlib.sha256(blob).hexdigest())+'\nV85R_BUNDLE = (\n'
encoded=base64.b85encode(blob).decode()
block+=''.join('    '+repr(encoded[n:n+110])+'\n' for n in range(0,len(encoded),110))+')\n'+end
if start in s:s=s[:s.index(start)]+block+s[s.index(end)+len(end):]
else:s=s.replace('# V85 NAS-local stitching.',block+'\n\n# V85 NAS-local stitching.')
client.write_text(s)
pin = root.parents[2]/'backend/internal/api/nas_v85r_pin.go'
pin.write_text('// Code generated by clients/nas-pull/v85r/build.py; DO NOT EDIT.\npackage api\n\nconst nasStitchManifestSHA = '+json.dumps(hashlib.sha256(raw).hexdigest())+'\n')
print('V85r manifest',hashlib.sha256(raw).hexdigest(),'files',len(files),'bundle bytes',len(blob))
