"""Build the offline native Durham profile from the pinned V85r sources."""
import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile


ROOT = Path(__file__).resolve().parent
PIN_FILE = ROOT / "durham-arm64.json"
GO_PIN_FILE = ROOT.parents[2] / "backend/internal/api/nas_v85r_durham_pin.go"
LEGACY_EVALUATOR = "remeasure-linux-amd64"
EVALUATOR = "remeasure-linux-arm64"
EVALUATOR_SHA256 = "0c90ed4c9527e0f9b6eedc432b71dd581a4dac0f758850988df80d2e684b2fed"
DEBIAN_VERSION = "7.1.5-0+deb13u1"
DEBIAN_FFMPEG_SHA256 = "6ec9c42306df30803c731c9e53300627257fd59d2f5a80b394c14cec5fd6d5ef"


def digest(body):
    return hashlib.sha256(body).hexdigest()


def elf_arm64(body):
    return body[:6] == b"\x7fELF\x02\x01" and int.from_bytes(body[18:20], "little") == 183


def build_evaluator():
    with tempfile.TemporaryDirectory(prefix="durham-arm64-build-") as scratch:
        target = Path(scratch) / EVALUATOR
        subprocess.run(
            ["go", "build", "-trimpath", "-ldflags=-s -w -buildid=", "-o", str(target), "./cmd/remeasure"],
            cwd=ROOT / "producer", check=True, env=dict(
                os.environ, CGO_ENABLED="0", GOOS="linux", GOARCH="arm64",
                GOARM64="v8.0", GOTOOLCHAIN="go1.26.5",
            ),
        )
        return target.read_bytes()


def make_bundle(evaluator):
    if not elf_arm64(evaluator) or digest(evaluator) != EVALUATOR_SHA256:
        raise ValueError("native evaluator differs from the reviewed ARM64 build")
    manifest = json.loads((ROOT / "manifest.json").read_bytes())
    files = {name: (ROOT / name).read_bytes() for name in manifest["files"] if name != LEGACY_EVALUATOR}
    for name, body in files.items():
        if digest(body) != manifest["files"][name]:
            raise ValueError("source differs from the reviewed V85r manifest: " + name)
    # The archived adapter has two calls to the October evaluator. Retain its
    # exact classifier and retry logic, and bind both calls to the native build.
    runner = files["runner.py"]
    if runner.count(LEGACY_EVALUATOR.encode()) != 2:
        raise ValueError("unexpected V85r runner evaluator binding")
    files["runner.py"] = runner.replace(LEGACY_EVALUATOR.encode(), EVALUATOR.encode())
    files[EVALUATOR] = evaluator
    manifest["files"] = {name: digest(body) for name, body in files.items()}
    body = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    files["manifest.json"] = body
    archive_bytes = io.BytesIO()
    with tarfile.open(fileobj=archive_bytes, mode="w") as archive:
        for name, member in sorted(files.items()):
            info = tarfile.TarInfo(name)
            info.size = len(member)
            info.mode = 0o700 if name == EVALUATOR else 0o600
            archive.addfile(info, io.BytesIO(member))
    compressed = io.BytesIO()
    with gzip.GzipFile(filename="", fileobj=compressed, mode="wb", mtime=0) as output:
        output.write(archive_bytes.getbuffer())
    return compressed.getvalue(), digest(body)


def media_tool_pins(deb):
    if digest(deb.read_bytes()) != DEBIAN_FFMPEG_SHA256:
        raise ValueError("FFmpeg Debian package SHA-256 differs")
    data = subprocess.check_output(["ar", "-p", str(deb), "data.tar.xz"])
    result = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:xz") as archive:
        for name in ("ffmpeg", "ffprobe"):
            with archive.extractfile("./usr/bin/" + name) as tool:
                body = tool.read()
            if not elf_arm64(body):
                raise ValueError("Debian tool is not ELF ARM64: " + name)
            result[name] = {"sha256": digest(body), "size_bytes": len(body)}
    return result


def go_pins(pins):
    return (
        "// Code generated by clients/nas-pull/v85r/build_durham.py; DO NOT EDIT.\n"
        "package api\n\n"
        f'const nasDurhamManifestSHA = "{pins["manifest_sha256"]}"\n'
        f'const nasDurhamEvaluatorSHA = "{pins["evaluator_sha256"]}"\n'
        f'const nasDurhamToolVersion = "{pins["media_tool_version"]}"\n'
        f'const nasDurhamFFmpegSHA = "{pins["tools"]["ffmpeg"]["sha256"]}"\n'
        f'const nasDurhamFFprobeSHA = "{pins["tools"]["ffprobe"]["sha256"]}"\n'
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ffmpeg-deb", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--evaluator", type=Path, help="reuse the exact verified ARM64 build")
    parser.add_argument("--write-pins", action="store_true")
    args = parser.parse_args()
    evaluator = args.evaluator.read_bytes() if args.evaluator else build_evaluator()
    bundle, manifest = make_bundle(evaluator)
    pins = {
        "architecture": "linux-arm64",
        "bundle_sha256": digest(bundle),
        "bundle_size_bytes": len(bundle),
        "manifest_sha256": manifest,
        "evaluator_sha256": EVALUATOR_SHA256,
        "evaluator_size_bytes": len(evaluator),
        "media_tool_version": DEBIAN_VERSION,
        "tools": media_tool_pins(args.ffmpeg_deb),
    }
    expected = json.dumps(pins, indent=2, sort_keys=True) + "\n"
    go = go_pins(pins)
    if args.write_pins:
        PIN_FILE.write_text(expected)
        GO_PIN_FILE.write_text(go)
    elif PIN_FILE.read_text() != expected or GO_PIN_FILE.read_text() != go:
        raise SystemExit("Durham tools or bundle differ from the reviewed pins")
    with args.out.open("xb") as output:
        output.write(bundle)


if __name__ == "__main__":
    main()
